import { expect, expectNoOverflow, test } from './fixture'

test('tablet inspector opens in view, isolates keyboard controls and returns focus on dismissal', async ({ page }, testInfo) => {
  const narrow = testInfo.project.name === 'mobile'
  const viewport = narrow ? { width: 768, height: 700 } : { width: 1024, height: 600 }
  await page.setViewportSize(viewport)
  await page.goto('./#/labs/attention-debugger?preset=causal&step=2')
  const trigger = page.getByRole('button', { name: 'Inspector & math' })
  const inspector = page.getByRole('dialog', { name: 'Inspector & math' })
  const close = inspector.getByRole('button', { name: 'Close' })
  await trigger.click()
  await expect(inspector.getByRole('heading', { name: 'Key metrics' })).toBeInViewport()
  await expect(close).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await close.press('Escape')
  await expect(inspector).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(page.getByRole('slider', { name: 'Step', exact: true })).toHaveValue('2')

  await trigger.click()
  await page.mouse.click(10, Math.floor(viewport.height / 2))
  await expect(inspector).toBeHidden()
  await expect(trigger).toBeFocused()

  await trigger.click()
  await inspector.getByRole('heading', { name: 'Concept guide' }).scrollIntoViewIfNeeded()
  await expect(close).toBeInViewport()
  await close.click()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('tab', { name: 'Inspector & math' })).toBeFocused()
  await expect(page.getByRole('heading', { name: 'Key metrics' })).toBeInViewport()
  await expect(page.locator('dialog:modal')).toHaveCount(0)
  await page.setViewportSize(viewport)
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expectNoOverflow(page)
})

test('phone jumps between the graph and parameter tabs and keeps the selected experiment', async ({ page }, testInfo) => {
  const width = testInfo.project.name === 'mobile' ? 320 : 390
  await page.setViewportSize({ width, height: 568 })
  await page.goto('./#/labs/attention-debugger?preset=causal&step=2')
  const stage = page.getByRole('region', { name: 'Visualization' })
  const tab = page.getByRole('tab', { name: 'Controls' })
  await page.getByRole('button', { name: 'Jump to controls' }).click()
  await expect(tab).toBeInViewport()
  await expect(tab).toBeFocused()
  await tab.press('Tab')
  await expect(page.getByRole('tabpanel', { name: 'Controls' })).toBeFocused()
  const finalControl = page.getByRole('tabpanel', { name: 'Controls' }).locator('input, select, button').last()
  await finalControl.scrollIntoViewIfNeeded()
  await expect(tab).toBeInViewport()
  await tab.focus()
  await tab.press('ArrowRight')
  await expect(page.getByRole('heading', { name: 'Key metrics' })).toBeInViewport()
  await page.getByRole('button', { name: 'Back to visualization' }).click()
  await expect(stage).toBeFocused()
  await expect(stage.locator('.wb-stage-surface')).toBeInViewport()
  const next = page.getByRole('button', { name: 'Next step', exact: true })
  const target = await next.boundingBox()
  expect(target!.width).toBeGreaterThanOrEqual(44)
  expect(target!.height).toBeGreaterThanOrEqual(44)
  await next.click()
  await expect(page.getByRole('slider', { name: 'Step', exact: true })).toHaveValue('3')
  await expectNoOverflow(page)
})
