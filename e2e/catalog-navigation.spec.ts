import { LAB_REGISTRY } from '../src/labs/registry'
import { expect, test } from './fixture'

test('keeps a filtered catalog and restores focus to the card when returning from a lab', async ({ page }) => {
  await page.goto('./')
  const catalog = page.getByRole('region', { name: 'Lab explorer' })
  await catalog.getByRole('button', { name: /Sequence & Attention/ }).click()
  await catalog.getByRole('combobox', { name: 'Difficulty' }).selectOption('intermediate')
  const card = catalog.getByRole('link', { name: /Embeddings & RoPE Geometry/ })
  await expect(catalog.getByRole('status')).toHaveText(`Showing 1 of ${LAB_REGISTRY.length} labs`)
  await expect(catalog.getByRole('link')).toHaveCount(1)
  await card.press('Enter')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Embeddings & RoPE Geometry')
  await page.goBack()
  await expect(card).toBeFocused()
  await expect(catalog.getByRole('link')).toHaveCount(1)
  await page.reload()
  await expect(catalog.getByRole('combobox')).toHaveValue('intermediate')
  await expect(catalog.getByRole('link')).toHaveCount(1)
  await catalog.getByRole('button', { name: 'Clear filters' }).click()
  await expect(catalog.getByRole('link')).toHaveCount(LAB_REGISTRY.length)
  await expect(catalog.getByRole('heading', { level: 2 })).toBeFocused()
})

test('recovers from an empty search and finds presets by lab name across languages', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: '简体中文', exact: true }).click()
  const trigger = page.getByRole('button', { name: '命令面板' })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  const search = dialog.getByRole('combobox')
  await search.fill('unfindable-987654321')
  await expect(dialog.getByRole('status')).toContainText('没有匹配项')
  await dialog.getByRole('button', { name: '清除搜索' }).click()
  await expect(search).toBeFocused()
  await expect(search).toHaveValue('')
  await search.fill('量化 recovery')
  await expect(dialog.getByRole('option').first()).toContainText('分组 NF4 精度恢复')
  await search.press('Enter')
  await expect(page.locator('.wb-presets [aria-pressed=true]')).toHaveText('分组 NF4 精度恢复')
})

test('keeps the complete palette and the selected result in view on a short landscape screen', async ({ page }) => {
  await page.setViewportSize({ width: 667, height: 320 })
  await page.goto('./')
  await page.getByRole('button', { name: `Browse all ${LAB_REGISTRY.length} labs` }).click()
  const trigger = page.getByRole('button', { name: 'Command palette' })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  const search = dialog.getByRole('combobox')
  await search.press('ArrowUp')
  await expect(dialog.getByRole('option').last()).toHaveAttribute('aria-selected', 'true')
  const dialogRect = await dialog.boundingBox()
  const footer = await dialog.locator('.tl-palette-keys').boundingBox()
  const result = await dialog.getByRole('option', { selected: true }).boundingBox()
  expect(dialogRect).not.toBeNull()
  expect(footer).not.toBeNull()
  expect(result).not.toBeNull()
  expect(footer!.y + footer!.height).toBeLessThanOrEqual(dialogRect!.y + dialogRect!.height)
  expect(result!.y).toBeGreaterThan((await search.boundingBox())!.y)
  expect(result!.y + result!.height).toBeLessThanOrEqual(footer!.y + 1)
  const y = await page.evaluate(() => window.scrollY)
  await page.mouse.move(1, 2)
  await page.mouse.wheel(0, 300)
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  expect(await page.evaluate(() => window.scrollY)).toBe(y)
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  expect(await page.evaluate(() => window.scrollY)).toBe(y)
})
